ROLES = ["оператор", "оператор", "наладчик", "мастер"]

# Если рабочий ошибся с причиной, чаще всего он ставит «прочее» или «оператор».
WRONG_REASONS = ["other", "other", "operator", "quality_hold"]


def _add_typo(text: str, rng: np.random.Generator) -> str:
    """Одна опечатка: перестановка соседних букв."""
    letters = [i for i, ch in enumerate(text[:-1]) if ch.isalpha() and text[i + 1].isalpha()]
    if not letters:
        return text
    i = int(rng.choice(letters))
    return text[:i] + text[i + 1] + text[i] + text[i + 2 :]


def _casual(text: str, rng: np.random.Generator) -> str:
    """Неформальная запись: строчные буквы, сокращения, опечатки."""
    if rng.random() < 0.35:
        text = text.lower()
    if rng.random() < 0.2:
        text = text.replace("конвейер", "конв.").replace("оборудование", "обор.")
    if rng.random() < 0.15:
        text = _add_typo(text, rng)
    return text


def make_report_text(
    subtype: str, equipment_name: str, reason: str, rng: np.random.Generator
) -> dict[str, str | bool]:
    """Описание, действия, роль автора, выбранная причина и заполнен ли отчёт."""
    options = TEMPLATES.get(subtype) or TEMPLATES["микроостановка"]
    description, actions = options[int(rng.integers(len(options)))]
    description = _casual(description.format(name=equipment_name), rng)
    actions = _casual(actions.format(name=equipment_name), rng)

    completed = rng.random() < 0.92          # 8% отчётов остаются черновиками без описания
    chosen_reason = reason
    if completed and reason != "planned_maintenance" and rng.random() < 0.15:
        chosen_reason = str(rng.choice(WRONG_REASONS))   # 15% — неверно выбранная причина

    return {
        "description": description if completed else "",
        "actions_taken": actions if completed else "",
        "reporter_role": str(rng.choice(ROLES)) if completed else "",
        "reason": chosen_reason,
        "completed": completed,
    }
